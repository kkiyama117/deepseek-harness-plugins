#!/usr/bin/env node
// replay.mjs — trace -> Quint replay gate (mizchi's "implementation side" of
// the loop, closed on the agent's own phase-transition trace).
//
// The agent's actual workflow execution is a sequence of model actions. This
// generator turns that sequence into a deterministic Quint test that replays
// the EXACT transitions the agent performed and asserts every invariant holds
// after EVERY step. The model is the source of truth; the trace is the
// implementation under test.
//
//   - A `.then(step)` that fails  -> the model's guard blocked a transition the
//     agent attempted (deviation: e.g. implemented before approval, reviewed
//     before verify, reported twice). Gate RED.
//   - An `.expect(allInvariants)` that fails -> an invariant broke at some
//     state the agent reached. Gate RED.
//
// Usage:
//   node replay.mjs trace.json > replayTrace.qnt
//   node replay.mjs trace.jsonl > replayTrace.qnt
//   node replay.mjs --self-check
//   quint test replayTrace.qnt --main=replayTrace
//
// Trace format — a JSON array OR JSONL (one object per line). Action names
// and parameters match implementTask.qnt:
//   {"a":"scopeDone"}
//   {"a":"clarify","clear":true|false}
//   {"a":"clarifyAnswered"}
//   {"a":"plan","frontierOk":true|false}
//   {"a":"approve"}
//   {"a":"adjust"}
//   {"a":"skipGate"}                       // sets PRE_APPROVED = true
//   {"a":"delegate","w":<int>,"task":"ImplementTask"|"VerifyTask"}
//   {"a":"workerDone","w":<int>,"task":"ImplementTask"|"VerifyTask","ok":true|false}
//   {"a":"review","v":"Pass"|"Fail"}
//   {"a":"report"}
//
// PRE_APPROVED is inferred from whether the trace uses skipGate; WORKERS is
// the set of worker ids the trace references. BUGGY_FIX_CAP is always false —
// the gate replays against the real (fixed) model.

import { readFileSync } from 'node:fs';

const ALL_INV = [
  'fixRoundCap',
  'planRequiresClarify',
  'reviewOnlyAfterVerify',
  'reportRequiresReview',
  'noImplementBeforeApproval',
  'approveRequiresPlan',
  'reportHonesty',
  'workHappensInWorkers',
].join(' and ');

/** Parse a JSON array or JSONL (one object per line) into step objects. */
export function loadTrace(text) {
  const trimmed = text.trim();
  if (!trimmed) return [];
  if (trimmed.startsWith('[')) {
    const parsed = JSON.parse(trimmed);
    if (!Array.isArray(parsed)) throw new Error('trace JSON must be an array');
    return parsed;
  }
  return trimmed.split(/\r?\n/).filter((line) => line.trim()).map((line, i) => {
    let obj;
    try { obj = JSON.parse(line); } catch (e) {
      throw new Error(`trace line ${i + 1}: ${e.message}`);
    }
    if (obj === null || typeof obj !== 'object' || Array.isArray(obj)) {
      throw new Error(`trace line ${i + 1}: expected a JSON object`);
    }
    return obj;
  });
}

export function renderReplay(trace, sourceLabel) {
  const workers = new Set();
  let preApproved = false;

  const call = (s) => {
    switch (s.a) {
      case 'scopeDone': return 'scopeDone';
      case 'clarify': return `clarify(${s.clear})`;
      case 'clarifyAnswered': return 'clarifyAnswered';
      case 'plan': return `plan(${s.frontierOk})`;
      case 'approve': return 'approve';
      case 'adjust': return 'adjust';
      case 'skipGate': preApproved = true; return 'skipGate';
      case 'delegate': workers.add(s.w); return `delegate(${s.w}, ${s.task})`;
      case 'workerDone': workers.add(s.w); return `workerDone(${s.w}, ${s.task}, ${s.ok})`;
      case 'review': return `review(${s.v})`;
      case 'report': return 'report';
      default: throw new Error(`unknown action: ${s.a}`);
    }
  };

  const steps = trace.map(call);
  const workerSet =
    workers.size ? Array.from(workers).sort((a, b) => a - b).join(', ') : '1, 2';

  const chain = ['init', ...steps.flatMap((c) => [`.then(${c})`, '.expect(allInvariants)'])]
    .join('\n      ');

  return `// Auto-generated by replay.mjs from ${sourceLabel}.
// Gate: replay the agent's actual phase-transition trace in the formal model
// and assert every invariant holds after every step. A .then(step) fails when
// the model's guard blocks the transition the agent attempted (deviation); an
// .expect(allInvariants) fails when an invariant breaks. Either = gate RED.
module replayTrace {
  import implementTask(PRE_APPROVED = ${preApproved}, WORKERS = Set(${workerSet}), BUGGY_FIX_CAP = false).* from "../implementTask"

  val allInvariants: bool = ${ALL_INV}

  run replayTest =
    ${chain}
}
`;
}

const arg = process.argv[2];
if (!arg) {
  console.error('usage: replay.mjs <trace.json|trace.jsonl> | --self-check');
  process.exit(2);
}

if (arg === '--self-check') {
  const steps = [
    { a: 'scopeDone' },
    { a: 'clarify', clear: true },
    { a: 'plan', frontierOk: true },
    { a: 'approve' },
  ];
  const fromArray = renderReplay(loadTrace(JSON.stringify(steps)), 'array');
  const fromJsonl = renderReplay(loadTrace(steps.map((s) => JSON.stringify(s)).join('\n')), 'jsonl');
  const norm = (s) => s.replace(/from array\./, 'from x.').replace(/from jsonl\./, 'from x.');
  if (norm(fromArray) !== norm(fromJsonl)) {
    console.error('self-check: JSON array and JSONL traces rendered differently');
    process.exit(1);
  }
  if (!fromArray.includes('.then(approve)')) {
    console.error('self-check: missing approve step');
    process.exit(1);
  }
  console.log('ok');
  process.exit(0);
}

process.stdout.write(renderReplay(loadTrace(readFileSync(arg, 'utf8')), arg));
